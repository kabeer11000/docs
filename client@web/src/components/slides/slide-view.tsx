"use client";

import {
  type HTMLAttributes,
  memo,
  type ReactNode,
  useLayoutEffect,
  useMemo,
  useRef,
  useState,
} from "react";
import { backgroundCss, elementMarkup } from "@/lib/slides/elements";
import {
  LAYOUTS,
  type Layout,
  type Slide,
  type Theme,
} from "@/lib/slides/model";
import { SLIDE_CSS, SLIDE_H, SLIDE_W } from "@/lib/slides/styles";
import { cn } from "@/lib/utils";

export function useSize<T extends HTMLElement>() {
  const ref = useRef<T>(null);
  const [size, setSize] = useState({ w: 0, h: 0 });
  useLayoutEffect(() => {
    const el = ref.current;
    if (!el) return;
    const ro = new ResizeObserver(([entry]) =>
      setSize({ w: entry.contentRect.width, h: entry.contentRect.height }),
    );
    ro.observe(el);
    return () => ro.disconnect();
  }, []);
  return [ref, size] as const;
}

export const fitScale = (w: number, h: number) =>
  Math.max(0, Math.min(w / SLIDE_W, h / SLIDE_H));

/**
 * Injects generated markup: editor-schema HTML from the deck snapshot, or element markup built from validated
 * data (lib/slides/elements). Never pass stored, unvalidated HTML.
 */
export function Markup({
  html,
  as = "div",
  ...rest
}: { html: string; as?: "div" | "span" } & HTMLAttributes<HTMLElement>) {
  const Tag = as;
  // biome-ignore lint/security/noDangerouslySetInnerHtml: the one place generated slide markup is injected
  return <Tag {...rest} dangerouslySetInnerHTML={{ __html: html }} />;
}

/** The slide stylesheet, hoisted once into the document head by React. */
export const SlideStyles = () => (
  <style href="slides-css" precedence="default">
    {SLIDE_CSS}
  </style>
);

/**
 * A 1280x720 slide drawn at `scale`. `region` renders each region element (it must carry
 * className="sl-r" and data-region) so the editor and static views share one stylesheet.
 * `children` are drawn above the regions (free elements).
 */
export function SlideView({
  theme,
  layout,
  scale,
  region,
  background,
  className,
  children,
  overlay,
  radius = 0,
}: {
  theme: Theme;
  layout: Layout;
  scale: number;
  region: (name: string) => ReactNode;
  background?: string;
  className?: string;
  children?: ReactNode;
  /** Drawn over the slide in its own (unscaled, unclipped) box: selection frames, handles, toolbars. */
  overlay?: ReactNode;
  /** Corner radius in screen pixels (the slide clips its own content to it). */
  radius?: number;
}) {
  const bg = backgroundCss(background);
  return (
    <div
      className={cn(
        "relative shrink-0",
        !overlay && "overflow-hidden",
        className,
      )}
      style={{
        width: SLIDE_W * scale,
        height: SLIDE_H * scale,
        borderRadius: radius || undefined,
      }}
    >
      <SlideStyles />
      <div
        className="sl"
        data-theme={theme}
        data-layout={layout}
        style={{
          transform: `scale(${scale})`,
          transformOrigin: "0 0",
          ...(radius && scale ? { borderRadius: radius / scale } : {}),
          ...(bg ? { background: bg } : {}),
        }}
      >
        {LAYOUTS[layout].regions.map(region)}
        {children}
      </div>
      {overlay}
    </div>
  );
}

/**
 * A slide from the deck snapshot: region and text box HTML is schema-generated by the editor kit and element
 * markup is built from validated data, so both are safe to inject. No editor instances.
 */
export const StaticSlide = memo(function StaticSlide({
  slide,
  theme,
  scale,
  className,
  radius,
}: {
  slide: Slide;
  theme: Theme;
  scale: number;
  className?: string;
  radius?: number;
}) {
  const elements = useMemo(
    () => slide.elements.map(elementMarkup).join(""),
    [slide.elements],
  );
  return (
    <SlideView
      theme={theme}
      layout={slide.layout}
      scale={scale}
      background={slide.background}
      className={className}
      radius={radius}
      region={(r) => (
        <div key={r} className="sl-r" data-region={r}>
          <Markup html={slide.html[r] ?? ""} />
        </div>
      )}
    >
      {elements && <Markup html={elements} />}
    </SlideView>
  );
});
