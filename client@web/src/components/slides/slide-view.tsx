"use client";

import { type ReactNode, useLayoutEffect, useRef, useState } from "react";
import { type Layout, LAYOUTS, type Slide, type Theme } from "@/lib/slides/model";
import { SLIDE_CSS, SLIDE_H, SLIDE_W } from "@/lib/slides/styles";
import { cn } from "@/lib/utils";

export function useSize<T extends HTMLElement>() {
  const ref = useRef<T>(null);
  const [size, setSize] = useState({ w: 0, h: 0 });
  useLayoutEffect(() => {
    const el = ref.current;
    if (!el) return;
    const ro = new ResizeObserver(([entry]) => setSize({ w: entry.contentRect.width, h: entry.contentRect.height }));
    ro.observe(el);
    return () => ro.disconnect();
  }, []);
  return [ref, size] as const;
}

export const fitScale = (w: number, h: number) => Math.max(0, Math.min(w / SLIDE_W, h / SLIDE_H));

/**
 * A 1280x720 slide drawn at `scale`. `region` renders each region element (it must carry
 * className="sl-r" and data-region) so the editor and static views share one stylesheet.
 */
export function SlideView({
  theme,
  layout,
  scale,
  region,
  className,
}: {
  theme: Theme;
  layout: Layout;
  scale: number;
  region: (name: string) => ReactNode;
  className?: string;
}) {
  return (
    <div className={cn("relative shrink-0 overflow-hidden", className)} style={{ width: SLIDE_W * scale, height: SLIDE_H * scale }}>
      <style href="slides-css" precedence="default">
        {SLIDE_CSS}
      </style>
      <div className="sl" data-theme={theme} data-layout={layout} style={{ transform: `scale(${scale})`, transformOrigin: "0 0" }}>
        {LAYOUTS[layout].regions.map(region)}
      </div>
    </div>
  );
}

/** Region HTML from the deck snapshot (schema-generated by the editor kit, so it is safe to inject). */
export function StaticSlide({ slide, theme, scale, className }: { slide: Slide; theme: Theme; scale: number; className?: string }) {
  return (
    <SlideView
      theme={theme}
      layout={slide.layout}
      scale={scale}
      className={className}
      region={(r) => (
        <div key={r} className="sl-r" data-region={r}>
          <div dangerouslySetInnerHTML={{ __html: slide.html[r] ?? "" }} />
        </div>
      )}
    />
  );
}
